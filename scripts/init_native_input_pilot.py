#!/usr/bin/env python3
"""Explicit native macOS mouse/key pilot; fail closed until OS permissions.

Requires a user-selected and already-running foreground Player PID. Pixels
must visibly change within an explicit target ROI. Never reuses scripted
gameplay control as hardware input.
"""
import argparse
import json
from pathlib import Path
import sys


def output(path,data):
    path.write_text(json.dumps(data,indent=2)+"\n")


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--game-root",type=Path,required=True)
    ap.add_argument("--app",type=Path,required=True)
    ap.add_argument("--pid",type=int,required=True)
    ap.add_argument("--roi",type=int,nargs=4,metavar=("X","Y","WIDTH","HEIGHT"),required=True)
    sub=ap.add_mutually_exclusive_group(required=True)
    sub.add_argument("--key",type=int)
    sub.add_argument("--drag",type=float,nargs=4,metavar=("X0","Y0","X1","Y1"))
    ap.add_argument("--out",type=Path,required=True)
    ap.add_argument("--minimum-changed-fraction",type=float,default=.01)
    args=ap.parse_args()
    game=args.game_root.resolve(strict=True)
    app=args.app.resolve(strict=True)
    out=args.out.expanduser().resolve()
    if app.suffix!=".app" or not app.is_relative_to(game):
        ap.error("game App must reside inside game root")
    if out==game or out.is_relative_to(game):
        ap.error("Harness state must not be stored inside live game root")
    if args.pid<=0: ap.error("target PID must be positive")
    if not 0<args.minimum_changed_fraction<=.5:
        ap.error("expected visual change must be in (0,.5]")
    if min(args.roi[2:])<64:
        ap.error("ROI must cover at least 64x64 pixels")
    out.joinpath("contracts").mkdir(parents=True,exist_ok=True)
    out.joinpath("runtime").mkdir(exist_ok=True)
    config={"version":1,"adapters":{"input":{
       "type":"json-process","command":sys.executable,
       "args":[str(Path(__file__).with_name("native_input_qa.py"))],
       "actions":["native-input"],"timeoutMs":150000,
       "env":{"HARNESS_OS_INPUT_APPROVED":"1"}}
    }}
    # Environment flag is explicit per per-contract adapter and should only
    # be generated by the user invoking this dedicated opt-in CLI.
    output(out/"config.json",config)
    gesture="key" if args.key is not None else "drag"
    params={
      "allowedGameRoot":str(game),"appPath":str(app),
      "pid":args.pid,"gesture":gesture,
      "region":args.roi,
      "minimumChangedFraction":args.minimum_changed_fraction
    }
    if gesture=="key":params["keyCode"]=args.key
    else:params["points"]=args.drag
    task={
      "id":"T-NATIVE-INPUT",
      "title":"Real macOS input and visible Player response",
      "goal":"Verify foreground App receives native CGEvent and displays consequence",
      "kind":"qa","dependencies":[],"maxAttempts":1,
      "acceptanceCriteria":[{"id":"A1","description":"Accessibility-authorized native OS event and actual image difference",
         "requiredEvidence":["runtime-observation"],"requireVerifiedEvidence":True}],
      "execution":{"steps":[{"id":"native-input","adapter":"input","action":"native-input",
        "criterionId":"A1","evidenceType":"runtime-observation","input":params}]}
    }
    output(out/"contracts"/"native.json",task)
    print("NATIVE_INPUT_PILOT_CREATED",str(out))
    print("REQUIRES_ACCESSIBILITY_AND_SCREEN_RECORDING_PERMISSION")


if __name__=="__main__":
    main()
